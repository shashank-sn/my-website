#!/usr/bin/env node
// Generates posthog-config.js from .env
// Run: node scripts/build-posthog-config.js
const fs = require('fs');
const path = require('path');

const envPath = path.join(__dirname, '..', '.env');
const outPath = path.join(__dirname, '..', 'posthog-config.js');

const env = {};
if (fs.existsSync(envPath)) {
  fs.readFileSync(envPath, 'utf8').split('\n').forEach(line => {
    const [key, ...rest] = line.split('=');
    if (key && rest.length) env[key.trim()] = rest.join('=').trim();
  });
}

const apiKey = env.POSTHOG_API_KEY || '';
const host = env.POSTHOG_HOST || '';

if (!apiKey || !host) {
  console.error('Missing POSTHOG_API_KEY or POSTHOG_HOST in .env');
  process.exit(1);
}

const output = `// Auto-generated by scripts/build-posthog-config.js — do not edit manually
// Re-generate after changing .env: node scripts/build-posthog-config.js
window.POSTHOG_API_KEY = '${apiKey}';
window.POSTHOG_HOST = '${host}';
`;

fs.writeFileSync(outPath, output);
console.log('posthog-config.js written.');
